#!/usr/bin/env python3
"""Builds frontend/dist/css/purple.css from the light theme.

The light theme uses a lot of blue and blue-gray shades. Rather than keep a
second copy by hand, this script copies every colour declaration from
base.css and theme.css, in the same order, under :root[data-theme="purple"],
and turns the blues and blue-grays purple (the same palette LedgerLeaf uses).
Keeping the order means the purple rules override each other exactly the way
the light ones do.

Run it again after changing colours in base.css or theme.css:
    python3 scripts/make-purple-theme.py
"""
import colorsys
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
CSS = ROOT / "frontend" / "dist" / "css"
SOURCES = ["base.css", "theme.css"]
OUT = CSS / "purple.css"
SCOPE = ':root[data-theme="purple"]'

COLOR_PROPS = re.compile(
    r"^(--[\w-]+|color|background(-color|-image)?|border(-(top|right|bottom|left))?(-color)?|"
    r"border-image(-source)?|outline(-color)?|box-shadow|text-shadow|fill|stroke|caret-color|accent-color|"
    r"text-decoration(-color)?|column-rule(-color)?)$"
)

# A few exact matches so the main colours are LedgerLeaf's own.
EXACT = {
    "#2563eb": "#7446c9", "#1d4ed8": "#5f35af", "#0878f9": "#7446c9",
    "#0878e9": "#7446c9", "#005fca": "#5f35af", "#eff6ff": "#f4eefb",
}


def shift(r, g, b):
    h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
    deg = h * 360
    if not (190 <= deg <= 255) or s < 0.10:
        return None
    deg = 262 + (deg - 215) * 0.25
    s = s * (0.6 if s > 0.6 else 0.8)
    r2, g2, b2 = colorsys.hls_to_rgb(deg / 360, l, s)
    return round(r2 * 255), round(g2 * 255), round(b2 * 255)


def hex_color(m):
    text = m.group(0)
    if text.lower() in EXACT:
        return EXACT[text.lower()]
    h = text[1:]
    alpha = ""
    if len(h) in (3, 4):
        alpha = h[3:] * 2 if len(h) == 4 else ""
        h = "".join(c * 2 for c in h[:3])
    elif len(h) == 8:
        h, alpha = h[:6], h[6:]
    new = shift(int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))
    if not new:
        return text
    return "#%02x%02x%02x%s" % (*new, alpha)


def rgb_color(m):
    parts = [p.strip() for p in m.group(2).split(",")]
    try:
        r, g, b = (int(float(p)) for p in parts[:3])
    except ValueError:
        return m.group(0)
    new = shift(r, g, b)
    if not new:
        return m.group(0)
    rest = parts[3:]
    return "%s(%s)" % (m.group(1), ", ".join([str(v) for v in new] + rest))


def recolor(value):
    value = re.sub(r"#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3,4}\b", hex_color, value)
    return re.sub(r"(rgba?)\(([^)]*)\)", rgb_color, value)


def scoped(selector):
    sel = selector.strip()
    if 'data-theme=' in sel:
        return None
    if sel.startswith(":root"):
        return SCOPE + sel[len(":root"):]
    if sel == "html" or sel.startswith("html ") or sel.startswith("html,"):
        return SCOPE + sel[len("html"):]
    return SCOPE + " " + sel


def strip_comments(css):
    return re.sub(r"/\*.*?\*/", "", css, flags=re.S)


def blocks(css):
    """Yields (prelude, body) pairs for one nesting level."""
    i, n = 0, len(css)
    while i < n:
        j = css.find("{", i)
        if j < 0:
            return
        prelude = css[i:j].strip()
        depth, k = 1, j + 1
        while k < n and depth:
            if css[k] == "{":
                depth += 1
            elif css[k] == "}":
                depth -= 1
            k += 1
        yield prelude, css[j + 1:k - 1]
        i = k


def declarations(body):
    out = []
    for decl in re.split(r";(?![^(]*\))", body):
        if ":" not in decl:
            continue
        prop, value = decl.split(":", 1)
        prop = prop.strip()
        if COLOR_PROPS.match(prop.lower()):
            out.append("%s: %s" % (prop, recolor(value.strip())))
    return out


def convert(css, indent=""):
    lines = []
    for prelude, body in blocks(css):
        if prelude.startswith("@media") or prelude.startswith("@supports"):
            inner = convert(body, indent + "  ")
            if inner:
                lines.append("%s%s {" % (indent, prelude))
                lines.extend(inner)
                lines.append(indent + "}")
            continue
        if prelude.startswith("@"):
            continue  # keyframes, font-face
        selectors = [s for s in (scoped(p) for p in prelude.split(",")) if s]
        decls = declarations(body)
        if selectors and decls:
            lines.append("%s%s { %s; }" % (indent, ", ".join(selectors), "; ".join(decls)))
    return lines


def main():
    out = [
        "/* Purple theme. Generated by scripts/make-purple-theme.py from",
        "   base.css and theme.css; edit those and run the script again. */",
    ]
    for name in SOURCES:
        out.append("")
        out.append("/* from %s */" % name)
        out.extend(convert(strip_comments((CSS / name).read_text())))
    extra = CSS / "purple-extra.css"
    if extra.exists():
        out.append("")
        out.append("/* from purple-extra.css */")
        out.append(extra.read_text().strip())
    OUT.write_text("\n".join(out) + "\n")
    print("wrote", OUT.relative_to(ROOT), sum(1 for _ in out), "lines")


if __name__ == "__main__":
    main()
